// Copies the live contracts' generated code (no keys) and their deployment records into the web
// app, so the site builds on its own: the two demo ballots, and Tell Desk with its public-state
// reader (desk/src/view.ts, codec.ts) under vendor/desk.
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const keys = path.resolve(here, '../../zoo/keys');
for (const c of ['ballot-leaky', 'ballot-fixed']) {
  const src = path.join(keys, c, 'contract');
  if (!fs.existsSync(src)) continue;
  const dst = path.resolve(here, '../lib/contracts', c, 'contract');
  fs.mkdirSync(dst, { recursive: true });
  for (const f of ['index.js', 'index.d.ts']) fs.copyFileSync(path.join(src, f), path.join(dst, f));
}
// Preprod wins when both exist: it is where the live demo runs.
const out = path.resolve(here, '../data/deployments.json');
const pick = ['preprod', 'preview']
  .map((n) => [n, path.resolve(here, '../../chain', n === 'preview' ? 'deployments.json' : `deployments-${n}.json`)])
  .find(([, f]) => fs.existsSync(f) && Object.keys(JSON.parse(fs.readFileSync(f, 'utf8'))).length > 0);
if (pick) fs.writeFileSync(out, JSON.stringify({ network: pick[0], contracts: JSON.parse(fs.readFileSync(pick[1], 'utf8')) }, null, 2) + '\n');
else if (!fs.existsSync(out)) fs.writeFileSync(out, '{}\n');

// Tell Desk: generated contract code (desk/managed is built by `npm run compact -w desk`).
const deskManaged = path.resolve(here, '../../desk/managed/desk/contract');
if (fs.existsSync(path.join(deskManaged, 'index.js'))) {
  const dst = path.resolve(here, '../lib/contracts/desk/contract');
  fs.mkdirSync(dst, { recursive: true });
  for (const f of ['index.js', 'index.d.ts']) fs.copyFileSync(path.join(deskManaged, f), path.join(dst, f));
}
// Desk's public-state reader and Web Crypto codec, pointed at the copied contract code.
const deskSrc = path.resolve(here, '../../desk/src');
if (fs.existsSync(path.join(deskSrc, 'view.ts'))) {
  const dst = path.resolve(here, '../vendor/desk');
  fs.mkdirSync(dst, { recursive: true });
  for (const f of ['view.ts', 'codec.ts']) fs.copyFileSync(path.join(deskSrc, f), path.join(dst, f));
  fs.writeFileSync(
    path.join(dst, 'contract.ts'),
    "// Generated by web/scripts/contracts.mjs: Desk's contract code, as copied into lib/contracts/desk.\nexport { Contract, ledger, pureCircuits, Status } from '../../lib/contracts/desk/contract/index.js';\nexport type { Ledger, Finding, Opening, Report, Grade, Witnesses } from '../../lib/contracts/desk/contract/index.js';\n",
  );
  fs.writeFileSync(path.join(dst, 'README.md'), 'Generated copy of ../../desk/src/{view,codec}.ts (scripts/contracts.mjs). Edit them in desk/, not here.\n');
}
// Desk's deployment record (address, demo steps, published reports and grades).
const deskDep = ['preprod', 'preview'].map((n) => path.resolve(here, '../../chain', `desk-${n}.json`)).find((f) => fs.existsSync(f));
if (deskDep) {
  // Publish the deployment record without anything a sealed report keeps private: a report's digest
  // stays off the site until it is revealed on chain, when anyone can read it there anyway.
  const dep = JSON.parse(fs.readFileSync(deskDep, 'utf8'));
  for (const r of Object.values(dep.reports ?? {})) if (!r.revealed) delete r.digest;
  fs.writeFileSync(path.resolve(here, '../data/desk-deployment.json'), JSON.stringify(dep, null, 2) + '
');
}
else if (!fs.existsSync(path.resolve(here, '../data/desk-deployment.json'))) fs.writeFileSync(path.resolve(here, '../data/desk-deployment.json'), '{}\n');
console.log('contracts copied');
