// Tell Desk compiled with a newer compiler (0.35.0 or 0.36.0) and run on the runtime that
// compiler targets (compact-runtime 0.20 or 0.21), whose circuits are async and whose circuit
// context takes an options object. The full suite (test/desk.test.ts) runs on 0.31.1, the
// ledger live today; this one checks the same contract still behaves under the next compilers:
// the lifecycle, the main rejections, and an attacker who reads only public data.
//
//   compact compile +0.36.0 --skip-zk contracts/desk.compact compat/managed/desk
//   npm install --no-save --prefix compat @midnight-ntwrk/compact-runtime@0.21.0
//   npx vitest run --config compat/vitest.config.ts

import { describe, it, expect, beforeEach } from 'vitest';
import { createCircuitContext, createConstructorContext, dummyContractAddress } from '@midnight-ntwrk/compact-runtime';
// generated by the compile step above (git-ignored, like desk/managed)
import * as Desk from './managed/desk/contract/index.js';
import { witnesses, type DeskPrivateState } from '../src/witnesses.js';
import { gradeToNumber, projectId, randomBytes32, reportDigest, toHex } from '../src/codec.js';

const COIN_PK = '00'.repeat(32);
const DAY = 86_400;
const EMBARGO = 90n * BigInt(DAY);
const REPO_A = 'https://github.com/example-org/sealed-bids';
const REPO_B = 'https://github.com/another-team/payroll';
const TEXT = 'bid() writes hash(bid) to the ledger; bids are below 10,000, so a table of 10,000 hashes recovers every bid.';

type Opening = { finding: { digest: Uint8Array; project: Uint8Array }; nonce: Uint8Array };
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Any = any;

// The same simulator as src/simulator.ts, on the newer runtime's API.
class Sim {
  time = 1_790_000_000;
  readonly address = dummyContractAddress();
  readonly views: { circuit: string; view: unknown }[] = [];
  private constructor(
    readonly contract: Any,
    private state: Any,
  ) {}

  static async deploy(attesterHash: Uint8Array, embargo: bigint): Promise<Sim> {
    const c = new Desk.Contract(witnesses);
    const r = await c.initialState(createConstructorContext({ openings: {} } as DeskPrivateState, COIN_PK), attesterHash, embargo);
    return new Sim(c, r.currentContractState.data);
  }

  get ledger(): Any {
    return Desk.ledger(this.state);
  }
  get publicState(): Any {
    return this.state;
  }
  advance(s: number) {
    this.time += s;
  }

  async call(who: DeskPrivateState, circuit: string, ...args: unknown[]): Promise<{ result: unknown; privateState: DeskPrivateState }> {
    const ctx = createCircuitContext({
      circuitId: circuit,
      contractAddress: this.address,
      coinPublicKeyOrZswapState: COIN_PK,
      contractState: this.state,
      privateState: who,
      time: this.time,
    } as Any);
    const r = await this.contract.impureCircuits[circuit](ctx, ...args);
    this.state = r.context.callContext.currentQueryContext.state;
    // what the network sees of the call: inputs, outputs and the public transcript (never the
    // private transcript outputs, which stay with the prover)
    const trace = (r.context.callProofDataTrace ?? []).map((p: Any) => ({ input: p.input, output: p.output, transcript: p.publicTranscript }));
    this.views.push({ circuit, view: trace });
    return { result: r.result, privateState: r.context.callContext.currentPrivateState };
  }
}

// Every byte string and number in a value.
function atoms(x: unknown, out: string[] = [], seen = new Set<unknown>()): string[] {
  if (x === null || x === undefined) return out;
  if (x instanceof Uint8Array) return (out.push(toHex(x)), out);
  if (typeof x === 'bigint') return (out.push(x.toString(16)), out);
  if (typeof x !== 'object' || seen.has(x)) return out;
  seen.add(x);
  if (x instanceof Map) for (const [k, v] of x) (atoms(k, out, seen), atoms(v, out, seen));
  else if (Array.isArray(x)) for (const v of x) atoms(v, out, seen);
  else for (const v of Object.values(x)) atoms(v, out, seen);
  return out;
}
const publicAtoms = (sim: Sim) => {
  const s = sim.publicState as Any;
  return [...atoms((s.state ?? s).encode()), ...sim.views.flatMap((v) => atoms(v.view))];
};
function appears(secret: Uint8Array, haystack: string[]): boolean {
  const pieces = [secret.slice(0, 16), secret.slice(16), Uint8Array.from(secret).reverse().slice(0, 16)].map(toHex);
  return haystack.some((h) => pieces.some((p) => h.includes(p)));
}

async function world() {
  const attesterSecret = randomBytes32();
  const sim = await Sim.deploy(Desk.pureCircuits.attesterKey(attesterSecret), EMBARGO);
  const tell: DeskPrivateState = { attesterSecret, openings: {} };
  const researcher: DeskPrivateState = { researcherSecret: randomBytes32(), openings: {} };
  const maintainerA: DeskPrivateState = { maintainerSecret: randomBytes32(), openings: {} };
  const maintainerB: DeskPrivateState = { maintainerSecret: randomBytes32(), openings: {} };
  const projectA = await projectId(REPO_A);
  const projectB = await projectId(REPO_B);
  await sim.call(tell, 'registerMaintainer', Desk.pureCircuits.maintainerLeaf(maintainerA.maintainerSecret!, projectA));
  await sim.call(tell, 'registerMaintainer', Desk.pureCircuits.maintainerLeaf(maintainerB.maintainerSecret!, projectB));
  const now = () => BigInt(sim.time);
  const seal = async (who: DeskPrivateState, text: string, repo: string, to?: DeskPrivateState) => {
    const opening: Opening = { finding: { digest: await reportDigest(text), project: await projectId(repo) }, nonce: randomBytes32() };
    who.draft = opening;
    const { result } = await sim.call(who, 'seal', now());
    const id = result as Uint8Array;
    who.draft = undefined;
    who.openings[toHex(id)] = opening;
    if (to) to.openings[toHex(id)] = opening;
    return { id, opening };
  };
  return { sim, tell, researcher, maintainerA, maintainerB, projectA, projectB, now, seal };
}
type World = Awaited<ReturnType<typeof world>>;
const report = (w: World, id: Uint8Array) => w.sim.ledger.reports.lookup(id);

describe('Desk on the newer runtime', () => {
  let w: World;
  beforeEach(async () => {
    w = await world();
  });

  it('seal, acknowledge, fix, reveal: the opening on the ledger matches the seal', async () => {
    const { id, opening } = await w.seal(w.researcher, TEXT, REPO_A, w.maintainerA);
    expect(toHex(id)).toBe(toHex(Desk.pureCircuits.sealOf(opening)));
    expect(report(w, id).status).toBe(Desk.Status.pending);
    expect(w.sim.ledger.sealedCount).toBe(1n);
    w.sim.advance(2 * DAY);
    await w.sim.call(w.maintainerA, 'acknowledge', id, w.now());
    expect(report(w, id).status).toBe(Desk.Status.acknowledged);
    await w.sim.call(w.maintainerA, 'markFixed', id, w.now());
    expect(report(w, id).status).toBe(Desk.Status.fixed);
    await w.sim.call(w.researcher, 'reveal', id, opening);
    const o = w.sim.ledger.openings.lookup(id);
    expect(toHex(o.finding.digest)).toBe(toHex(await reportDigest(TEXT)));
    expect(toHex(o.finding.project)).toBe(toHex(w.projectA));
    expect(toHex(Desk.pureCircuits.sealOf(o))).toBe(toHex(id));
  });

  it('the embargo holds until it ends', async () => {
    const { id, opening } = await w.seal(w.researcher, TEXT, REPO_A, w.maintainerA);
    w.sim.advance(Number(EMBARGO) - 60);
    await expect(w.sim.call(w.researcher, 'reveal', id, opening)).rejects.toThrow(/still under embargo/);
    w.sim.advance(60);
    await w.sim.call(w.researcher, 'reveal', id, opening);
    expect(w.sim.ledger.openings.member(id)).toBe(true);
  });

  it('rejects a maintainer of another project, an impostor attester and a second acknowledgement', async () => {
    const { id } = await w.seal(w.researcher, TEXT, REPO_A, w.maintainerA);
    w.maintainerB.openings[toHex(id)] = w.maintainerA.openings[toHex(id)];
    await expect(w.sim.call(w.maintainerB, 'acknowledge', id, w.now())).rejects.toThrow(/not registered/);
    await w.sim.call(w.maintainerA, 'acknowledge', id, w.now());
    await expect(w.sim.call(w.maintainerA, 'acknowledge', id, w.now())).rejects.toThrow(/not awaiting acknowledgement/);
    await expect(w.sim.call({ attesterSecret: randomBytes32(), openings: {} }, 'attest', randomBytes32(), 0n, 1n, 1n)).rejects.toThrow(/not the attester/);
  });

  it('records grades by code hash; a later scan replaces an earlier one, a stale one is refused', async () => {
    const code = randomBytes32();
    await w.sim.call(w.tell, 'attest', code, gradeToNumber('C'), 3n, 10n);
    await w.sim.call(w.tell, 'attest', code, gradeToNumber('A'), 4n, 11n);
    expect(w.sim.ledger.grades.lookup(code).grade).toBe(gradeToNumber('A'));
    await expect(w.sim.call(w.tell, 'attest', code, gradeToNumber('F'), 4n, 9n)).rejects.toThrow(/later scan/);
    await w.sim.call(w.maintainerA, 'selfGrade', code, w.projectA, gradeToNumber('B'), 4n, 1n);
    expect(w.sim.ledger.selfGrades.lookup(code).selfReported).toBe(true);
  });

  it('an attacker reading only public data never sees the secrets or the pending report', async () => {
    const { id, opening } = await w.seal(w.researcher, TEXT, REPO_A, w.maintainerA);
    await w.sim.call(w.maintainerA, 'acknowledge', id, w.now());
    const pub = publicAtoms(w.sim);
    // control: the report id is public
    expect(pub.some((h) => h.includes(toHex(id)))).toBe(true);
    for (const secret of [w.researcher.researcherSecret!, w.maintainerA.maintainerSecret!, w.tell.attesterSecret!, opening.nonce, opening.finding.digest, opening.finding.project])
      expect(appears(secret, pub)).toBe(false);
  });
});
